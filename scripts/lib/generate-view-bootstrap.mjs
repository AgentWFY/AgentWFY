import { readFileSync, writeFileSync } from 'fs'
import { join } from 'path'

// Mirrors generate-system-config-keys.mjs: read the canonical source
// (shared/protocol/view-bootstrap.html) and emit a TS constant module so the
// renderer-side `view-document.ts` stays browser-safe (no fs at runtime). The
// Rust mobile handler reads the same .html via include_str!.

export function generateViewBootstrap(root) {
  const htmlPath = join(root, 'protocol', 'view-bootstrap.html')
  const html = readFileSync(htmlPath, 'utf-8')

  const body = `// AUTO-GENERATED by scripts/build from shared/protocol/view-bootstrap.html
// DO NOT EDIT — your changes will be overwritten on the next build.

export const VIEW_BOOTSTRAP_HTML = ${JSON.stringify(html)} as const
`

  const outPath = join(root, 'protocol', 'view-bootstrap.generated.ts')
  const existing = (() => { try { return readFileSync(outPath, 'utf-8') } catch { return null } })()
  if (existing !== body) writeFileSync(outPath, body)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = process.argv[2]
  if (!root) {
    console.error('Usage: generate-view-bootstrap.mjs <shared-dir>')
    process.exit(1)
  }
  generateViewBootstrap(root)
}
